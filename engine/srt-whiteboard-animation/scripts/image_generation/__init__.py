"""Image generation providers used by the video pipeline.

Two providers are wired today:

- ``sensenova`` -- SenseNova U1.5 Lite (default, supports true 16:9 2048x1152)
- ``zhipu``     -- Zhipu CogView-3-Flash (free tier, 1440x720 cropped to 16:9)

``ImageProviderChain`` implements the failover contract: a run is generated by
exactly one provider so the whole film keeps one visual language. Only the first
successful scene locks the provider; if the first scene fails, the chain falls
through to the next candidate *before* any frame has been accepted. Once locked,
later failures are raised instead of silently mixing two illustrators.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Callable, Iterable, Sequence

from .sensenova import SenseNovaImageProvider
from .zhipu import ZhipuImageProvider


IMAGE_PROVIDER_NAMES = ("sensenova", "zhipu")
DEFAULT_PROVIDER_CHAIN = ("sensenova", "zhipu")
AUTO_PROVIDER_ALIASES = {"auto", "chain", "fallback"}


def default_image_provider() -> str:
    """Resolve the CLI default from $IMAGE_PROVIDER (falls back to 'none').

    ``.env`` is loaded lazily here so the argparse default honours the project
    configuration without every entry point having to call ``load_project_env``.
    """

    try:
        from story.config import load_project_env

        load_project_env()
    except Exception:  # pragma: no cover - env loading is best effort
        pass

    raw = (os.getenv("IMAGE_PROVIDER") or "none").strip().lower()
    if raw in {"none", "auto"} or raw in IMAGE_PROVIDER_NAMES:
        return raw
    return "none"


def create_image_provider(name: str, **kwargs: Any):
    """Instantiate one provider by name."""

    key = (name or "").strip().lower()
    if key == "sensenova":
        return SenseNovaImageProvider(**kwargs)
    if key == "zhipu":
        return ZhipuImageProvider(**kwargs)
    raise ValueError(
        f"Unsupported image provider: {name!r}; expected one of "
        f"{IMAGE_PROVIDER_NAMES} or 'auto'"
    )


class ImageProviderChain:
    """Generate every scene with one locked provider, with startup failover."""

    def __init__(
        self,
        candidates: Sequence[str] | None = None,
        *,
        factory: Callable[..., Any] = create_image_provider,
        log: Callable[[str], None] | None = None,
    ):
        resolved = tuple(candidates or DEFAULT_PROVIDER_CHAIN)
        if not resolved:
            raise ValueError("Image provider chain requires at least one candidate")
        self.candidates = resolved
        self._factory = factory
        self._log = log or (lambda message: None)
        self._active_name: str | None = None
        self._providers: dict[str, Any] = {}
        self.attempts: list[dict[str, str]] = []

    @property
    def active_name(self) -> str | None:
        return self._active_name

    @property
    def active_provider(self):
        return self._providers.get(self._active_name) if self._active_name else None

    def generate(self, prompt: str, output_path: str | Path, **kwargs: Any) -> Path:
        if self._active_name:
            provider = self._providers[self._active_name]
            return provider.generate(prompt, output_path, **kwargs)

        errors: list[str] = []
        for name in self.candidates:
            try:
                provider = self._providers.get(name) or self._factory(name)
                self._providers[name] = provider
                path = provider.generate(prompt, output_path, **kwargs)
            except Exception as exc:  # noqa: BLE001 - failover must catch everything
                self.attempts.append({"provider": name, "result": f"failed: {exc}"})
                errors.append(f"{name}: {exc}")
                self._log(f"[warn] image provider {name} unavailable: {exc}")
                _cleanup(output_path)
                continue
            self.attempts.append({"provider": name, "result": "ok"})
            self._active_name = name
            self._log(f"[ok] image provider locked: {name}")
            return path

        raise RuntimeError(
            "No image provider could generate the first scene; tried "
            + "; ".join(errors)
        )

    def report(self) -> dict[str, Any]:
        provider = self.active_provider
        return {
            "provider": self._active_name,
            "candidates": list(self.candidates),
            "model": getattr(provider, "model", None) if provider else None,
            "attempts": list(self.attempts),
        }


def _cleanup(output_path: str | Path) -> None:
    """Remove a partial artifact so the next provider writes into a clean slot."""

    target = Path(output_path)
    if target.is_file():
        target.unlink(missing_ok=True)
    partial = target.with_name(target.name + ".part")
    if partial.is_file():
        partial.unlink(missing_ok=True)


