#!/usr/bin/env python3
"""Phase 32 MVP single-command entrypoint: topic -> Story -> SRT -> MP4.

Purpose:
    Provide one CLI that starts from a topic string and reuses the existing
    Story generator, Story schema, deterministic SRT converter, and video
    pipeline without introducing new providers, dependencies, or renderers.

Reuses:
    - story.generator.generate_story + story.router.create_story_provider
    - story_schema.validate_story (via generate_story)
    - story_pipeline.main_cli (which itself calls video_pipeline.main)
    - story_to_srt constants DEFAULT_CHARS_PER_SECOND / DEFAULT_PAUSE_MS

Non-goals / out of scope for this entrypoint:
    - No LLM providers are invoked implicitly; provider defaults to "mock".
    - No new orchestrator or pipeline contract integration.
    - No architecture refactor; the CLI delegates to existing modules.

Outputs (all confined under --output-dir):
    - story.json           (canonical Story JSON, generated by generate_story)
    - <story-stem>.srt     (deterministic SRT, written by story_pipeline)
    - .images/scene-NN.png (optional per-scene SenseNova images)
    - scene.json, .tts/, *-render.mp4, *-voice.m4a, *-final.mp4
                           (produced by video_pipeline.main)

Safety:
    - Refuses to write into historical phase32 output directories unless the
      user explicitly opts in with --allow-overwrite. This prevents the new
      CLI from silently clobbering existing reports, videos, or caches.
    - Refuses to run when the output directory already contains any files or
      subdirectories (e.g. scene.json, *.srt, *.mp4, *.m4a, .tts/) unless
      --allow-overwrite is given. Downstream video_pipeline would otherwise
      silently overwrite prior artifacts.
    - Refuses to overwrite an existing story JSON unless --allow-overwrite.
    - Confines --story-output and --srt-output to --output-dir: absolute
      paths, '..' traversal, and symlinks that escape are rejected.
    - Never deletes or modifies anything outside --output-dir.

CLI:
    python scripts/story_from_topic.py \\
        --topic "火箭发射" \\
        --provider mock \\
        --renderer auto \\
        --output-dir output/phase32-mvp
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Sequence

from image_generation import IMAGE_PROVIDER_NAMES, default_image_provider
from story.config import load_project_env
from story.generator import generate_story
from story.router import create_story_provider
from story_pipeline import main_cli as story_pipeline_main
from story_to_srt import DEFAULT_CHARS_PER_SECOND, DEFAULT_PAUSE_MS


# Repository root for this engine module. Anchored to the file location so the
# default output directory is stable regardless of the caller's cwd.
ENGINE_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT_DIR = ENGINE_ROOT / "output" / "phase32-mvp"
DEFAULT_STORY_FILENAME = "story.json"

# Historical Phase 32 output directories that already contain accepted reports
# and finished videos. Writing into these by default would clobber prior
# artifacts, so the CLI refuses unless --allow-overwrite is given.
PROTECTED_OUTPUT_DIR_NAMES = {
    "phase32",
    "phase32-test",
    "phase32b",
}


class CliError(ValueError):
    """User-facing CLI error, mapped to exit code 2 by main_cli()."""


def _resolve_output_dir(raw: str) -> Path:
    """Resolve --output-dir relative to ENGINE_ROOT when not absolute."""
    candidate = Path(raw)
    if not candidate.is_absolute():
        candidate = ENGINE_ROOT / candidate
    return candidate.resolve()


def _is_protected_output_dir(resolved: Path) -> bool:
    """Return True if resolved path is inside output/<protected-name>/."""
    try:
        rel = resolved.relative_to(ENGINE_ROOT / "output")
    except ValueError:
        return False
    return rel.parts and rel.parts[0] in PROTECTED_OUTPUT_DIR_NAMES


def _is_contained_in(path: Path, parent: Path) -> bool:
    """True if path is parent or a sub-path of parent.

    Both must already be resolved via Path.resolve() (symlinks and '..'
    canonicalized). Uses pathlib.relative_to for containment so the check is
    robust against prefix collisions (e.g. /foo/bar vs /foo/barrier).
    """
    try:
        path.relative_to(parent)
    except ValueError:
        return False
    return True


def _story_output_path(output_dir: Path, story_out: str | None) -> Path:
    """Resolve --story-output to a canonical path inside output_dir.

    Accepts either a bare filename (resolved against output_dir) or an
    absolute path (which must still resolve inside output_dir). Both '..'
    traversal and symlinks are canonicalized via Path.resolve() and the
    result is containment-checked with pathlib.relative_to, so prefix
    collisions (e.g. /out/foo vs /out/foobar) do not slip through.

    Raises CliError on any escape from output_dir.
    """
    if story_out is None:
        return output_dir / DEFAULT_STORY_FILENAME
    candidate = Path(story_out)
    if not candidate.is_absolute():
        candidate = output_dir / candidate
    resolved = candidate.resolve()
    if not _is_contained_in(resolved, output_dir):
        raise CliError(
            f"Story output path escapes --output-dir: {resolved} is not "
            f"under {output_dir}. Pass a path that stays inside --output-dir."
        )
    return resolved


def _srt_output_path(output_dir: Path, story_path: Path, srt_out: str | None) -> str:
    """Resolve --srt-output to a canonical string inside output_dir.

    Returns a plain string to match the existing story_pipeline contract,
    which accepts a filename or path and re-resolves internally. The
    containment check happens here so the CLI fails fast on escape attempts
    instead of letting downstream write outside --output-dir.

    Raises CliError on any escape from output_dir.
    """
    if srt_out is None:
        return str(output_dir / (story_path.stem + ".srt"))
    candidate = Path(srt_out)
    if not candidate.is_absolute():
        candidate = output_dir / candidate
    resolved = candidate.resolve()
    if not _is_contained_in(resolved, output_dir):
        raise CliError(
            f"SRT output path escapes --output-dir: {resolved} is not "
            f"under {output_dir}. Pass a path that stays inside --output-dir."
        )
    return str(resolved)


def build_story_json(topic: str, provider_name: str) -> dict:
    """Generate and validate a canonical Story JSON from a topic.

    Delegates to the existing provider router and generator; no logic is
    duplicated here. Raises StoryGenerationError / StoryValidationError on
    invalid input.
    """
    provider = create_story_provider(provider_name)
    return generate_story(topic, provider, provider_name=provider_name)


def write_story_json(story: dict, path: Path, *, allow_overwrite: bool) -> None:
    """Write story JSON to disk, refusing to clobber existing files."""
    if not allow_overwrite and path.exists():
        raise CliError(
            f"Story output file already exists at {path}. "
            "Re-run with a different --output-dir / --story-output, or pass "
            "--allow-overwrite to explicitly accept overwriting it."
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(story, ensure_ascii=False, indent=2) + "\n"
    path.write_text(payload, encoding="utf-8")


def _dispatch_to_video_pipeline(
    *,
    story_path: Path,
    output_dir: Path,
    srt_output: str,
    chars_per_second: float,
    pause_ms: int,
    renderer: str,
    tts_name: str | None,
    render_only: bool,
    env_py: str | None,
    asset_roots: Sequence[str],
    image: str | None,
    image_provider: str,
    resume: bool = False,
    voice_profile: str = "auto",
    visual_setting: str = "auto",
) -> int:
    """Call story_pipeline.main_cli with the flags this CLI exposes.

    story_pipeline.main_cli forwards these flags to video_pipeline.main and
    does not accept --video-pipeline-path; only flags documented by
    story_pipeline are emitted here.
    """
    argv: list[str] = [
        str(story_path),
        "--output",
        str(output_dir),
        "--srt-output",
        srt_output,
        "--chars-per-second",
        str(chars_per_second),
        "--pause-ms",
        str(pause_ms),
        "--renderer",
        renderer,
        "--image-provider",
        image_provider,
    ]
    # Only forward --tts when the caller actually chose one; downstream derives
    # the provider from --voice-profile when --tts is absent.
    if tts_name:
        argv += ["--tts", tts_name]
    if render_only:
        argv.append("--render-only")
    if env_py is not None:
        argv += ["--env-py", env_py]
    for root in asset_roots:
        argv += ["--asset-root", root]
    if image is not None:
        argv += ["--image", image]
    if resume:
        argv.append("--resume")
    argv += ["--voice-profile", voice_profile, "--visual-setting", visual_setting]
    return story_pipeline_main(argv)


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate a Story from a topic and run the video pipeline end-to-end.",
    )
    parser.add_argument(
        "--topic",
        required=True,
        help="Topic prompt passed to the Story provider.",
    )
    # Story generation defaults to the cheap text model configured in .env.
    # Set STORY_PROVIDER=zhipu to route story writing to GLM-4.7-Flash; an
    # explicit --provider still wins, and "mock" keeps the CLI offline.
    load_project_env()
    parser.add_argument(
        "--provider",
        default=os.getenv("STORY_PROVIDER", "mock"),
        help=(
            "Story provider name (default: $STORY_PROVIDER or mock). "
            "Real providers require env keys."
        ),
    )
    parser.add_argument(
        "--output-dir",
        default=str(DEFAULT_OUTPUT_DIR),
        help=(
            "Directory for all generated artifacts. Default: "
            f"{DEFAULT_OUTPUT_DIR}. Relative paths are resolved against the "
            "engine root."
        ),
    )
    parser.add_argument(
        "--story-output",
        default=None,
        help=(
            "Path of the Story JSON to write. Default: <output-dir>/story.json. "
            "Relative paths are resolved against --output-dir."
        ),
    )
    parser.add_argument(
        "--srt-output",
        default=None,
        help=(
            "SRT filename or path. Default: <output-dir>/<story-stem>.srt. "
            "Relative paths are resolved against --output-dir. Forwarded to "
            "story_pipeline."
        ),
    )
    parser.add_argument(
        "--renderer",
        default="auto",
        help="Renderer name or 'auto' (forwarded to video_pipeline).",
    )
    parser.add_argument(
        "--tts",
        choices=("audio8", "auto", "edge", "espeak", "piper"),
        default=None,
        help="TTS provider name forwarded to video_pipeline (default: from --voice-profile).",
    )
    parser.add_argument(
        "--voice-profile",
        default="auto",
        help=(
            "Narration voice preset, forwarded to video_pipeline. "
            "auto picks en-us-narrator for Latin-script narration and "
            "zh-cn-natural (local Audio8) for Chinese narration."
        ),
    )
    parser.add_argument(
        "--visual-setting",
        default="auto",
        help=(
            "Film-wide visual setting, forwarded to video_pipeline: auto derives "
            "one culture/cast/style block from the narration, none disables it, "
            "or pass a JSON path to reuse a previously reviewed setting."
        ),
    )
    parser.add_argument(
        "--image-provider",
        choices=("none", *IMAGE_PROVIDER_NAMES, "auto"),
        default=default_image_provider(),
        help=(
            "Generate a separate illustration for every scene: sensenova, zhipu, "
            "or auto (sensenova first, zhipu as failover). Requires an API key in .env."
        ),
    )
    parser.add_argument(
        "--render-only",
        action="store_true",
        help=(
            "Forwarded verbatim to video_pipeline. Semantics are defined by "
            "video_pipeline.main and are not interpreted here."
        ),
    )
    parser.add_argument(
        "--asset-root",
        action="append",
        default=[],
        help="Additional asset root; repeatable. Forwarded to video_pipeline.",
    )
    parser.add_argument(
        "--image",
        default=None,
        help="Optional explicit image path forwarded to video_pipeline.",
    )
    parser.add_argument(
        "--env-py",
        default=None,
        help="Python interpreter path forwarded to video_pipeline for helpers.",
    )
    parser.add_argument(
        "--chars-per-second",
        type=float,
        default=DEFAULT_CHARS_PER_SECOND,
        help=(
            f"Story->SRT cue rate (default: {DEFAULT_CHARS_PER_SECOND}). "
            "Forwarded to story_pipeline."
        ),
    )
    parser.add_argument(
        "--pause-ms",
        type=int,
        default=DEFAULT_PAUSE_MS,
        help=f"Story->SRT pause between cues (default: {DEFAULT_PAUSE_MS}).",
    )
    parser.add_argument(
        "--allow-overwrite",
        action="store_true",
        help=(
            "Allow writing into historical phase32 output directories and "
            "overwriting an existing story JSON. Off by default to protect "
            "prior artifacts."
        ),
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume an interrupted run from its existing story.json, SRT, and valid SenseNova images",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)

    if not args.topic.strip():
        print("[err] --topic must be a non-empty string", file=sys.stderr)
        return 2
    if args.image and args.image_provider != "none":
        raise CliError("--image and --image-provider cannot be used together")
    if args.resume and args.image_provider == "none":
        raise CliError("--resume requires an image provider")

    output_dir = _resolve_output_dir(args.output_dir)
    story_path = _story_output_path(output_dir, args.story_output)
    srt_output = _srt_output_path(output_dir, story_path, args.srt_output)

    # Refuse to write into protected historical output directories unless
    # the user explicitly opts in. This is the primary guard against
    # clobbering phase32 / phase32-test / phase32b artifacts.
    if not args.allow_overwrite and _is_protected_output_dir(output_dir):
        raise CliError(
            f"Refusing to write into protected historical output directory: {output_dir}. "
            f"Use a different --output-dir (default: {DEFAULT_OUTPUT_DIR}) or pass "
            "--allow-overwrite to accept the risk of overwriting prior artifacts."
        )

    # Refuse to run when the output directory already exists and contains any
    # files or subdirectories. Downstream video_pipeline writes scene.json,
    # *.srt, *.mp4, *.m4a, and .tts/ without existence checks, so any prior
    # content (even a partial story.json from a failed prior run) would be
    # silently overwritten. Check BEFORE mkdir so a race between this check
    # and any external writer is minimized; never delete, move, or clean
    # existing entries automatically.
    if args.resume and not story_path.is_file():
        raise CliError(f"Cannot resume: existing Story JSON was not found: {story_path}")

    if not args.allow_overwrite and not args.resume and output_dir.exists():
        try:
            entries = list(output_dir.iterdir())
        except NotADirectoryError as exc:
            raise CliError(
                f"Refusing to run: --output-dir {output_dir} exists but is not "
                f"a directory ({exc}). Choose a fresh, empty output directory."
            ) from exc
        if entries:
            preview = ", ".join(sorted(e.name for e in entries)[:8])
            more = "" if len(entries) <= 8 else f", ... (+{len(entries) - 8} more)"
            raise CliError(
                f"Refusing to run: --output-dir {output_dir} already contains "
                f"{len(entries)} entry(ies): {preview}{more}. "
                "Choose a fresh, empty output directory. No files were deleted."
            )

    # Create the output directory only after the empty-directory guard above.
    # With exist_ok=True, mkdir is idempotent for existing directories and
    # only fails if the path exists as a non-directory, in which case we
    # refuse with a clear message rather than letting OSError leak up.
    try:
        output_dir.mkdir(parents=True, exist_ok=True)
    except FileExistsError as exc:
        raise CliError(
            f"Refusing to run: --output-dir {output_dir} exists but is not a "
            f"directory ({exc}). Choose a different --output-dir."
        ) from exc

    if args.resume:
        print(f"[resume] reuse Story: {story_path}")
    else:
        try:
            story = build_story_json(args.topic.strip(), args.provider)
        except Exception as exc:  # noqa: BLE001 - top-level CLI error reporting
            print(f"[err] story generation failed: {exc}", file=sys.stderr)
            return 1

        try:
            write_story_json(story, story_path, allow_overwrite=args.allow_overwrite)
        except OSError as exc:
            print(f"[err] failed to write story JSON to {story_path}: {exc}", file=sys.stderr)
            return 1

    story = json.loads(story_path.read_text(encoding="utf-8-sig"))

    print(f"[ok] story: {story_path}")
    print(f"       title={story.get('title')!r} segments={len(story.get('segments', []))}")

    exit_code = _dispatch_to_video_pipeline(
        story_path=story_path,
        output_dir=output_dir,
        srt_output=srt_output,
        chars_per_second=args.chars_per_second,
        pause_ms=args.pause_ms,
        renderer=args.renderer,
        tts_name=args.tts,
        render_only=args.render_only,
        env_py=args.env_py,
        asset_roots=args.asset_root,
        image=args.image,
        image_provider=args.image_provider,
        resume=args.resume,
        voice_profile=args.voice_profile,
        visual_setting=args.visual_setting,
    )
    if exit_code != 0:
        print(f"[err] downstream pipeline exited with code {exit_code}", file=sys.stderr)
        return exit_code
    return 0


def main_cli(argv: Sequence[str] | None = None) -> int:
    """Top-level CLI wrapper that maps CliError to exit code 2."""
    try:
        return main(argv)
    except CliError as exc:
        print(f"[err] {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main_cli())
